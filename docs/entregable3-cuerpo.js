  '// mobile/src/infraestructura/api/ClienteChronova.ts',
  '',
  'export class ClienteChronova implements ApiDeChronova {',
  '  private urlBase = resolverUrlBase();',
  '  private token: string | null = null;',
  '',
  '  usarToken(token: string | null): void {',
  '    this.token = token;',
  '  }',
  '',
  '  private async pedir<T>(',
  "    metodo: 'GET' | 'POST' | 'PATCH' | 'DELETE',",
  '    ruta: string,',
  '    cuerpo?: unknown,',
  '  ): Promise<T> {',
  '    const controlador = new AbortController();',
  '    const temporizador = setTimeout(() => controlador.abort(), TIEMPO_MAXIMO_MS);',
  '',
  '    let respuesta: Response;',
  '    try {',
  '      respuesta = await fetch(`${this.urlBase}${ruta}`, {',
  '        method: metodo,',
  '        signal: controlador.signal,',
  '        headers: {',
  "          'Content-Type': 'application/json',",
  '          ...(this.token ? { Authorization: `Bearer ${this.token}` } : {}),',
  '        },',
  '        body: cuerpo === undefined ? undefined : JSON.stringify(cuerpo),',
  '      });',
  '    } catch (error) {',
  '      // El mensaje dice A DÓNDE se intentó llamar. Sin ese dato, una IP',
  '      // vieja y una caída real del servidor producen el mismo texto.',
  "      const agotado = error instanceof Error && error.name === 'AbortError';",
  '      throw new ErrorDeApi(',
  '        agotado',
  '          ? `El servidor no respondió a tiempo (${this.urlBase}).`',
  '          : `No pudimos conectarnos con el servidor (${this.urlBase}).`,',
  "        'SIN_CONEXION',",
  '      );',
  '    } finally {',
  '      clearTimeout(temporizador);',
  '    }',
  '',
  '    this.atenderRenovacion(respuesta);',
  '',
  '    const texto = await respuesta.text();',
  '    const datos = texto ? (JSON.parse(texto) as Record<string, any>) : {};',
